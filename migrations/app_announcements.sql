-- Minto What's New announcements.
-- Apply manually in Supabase SQL Editor before deploying this feature.
begin;

create table if not exists public.app_announcements (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(title) between 3 and 100),
    message text not null check (char_length(message) between 5 and 500),
    category text not null default 'Improvement'
        check (category in ('Feature', 'Improvement', 'Fix', 'Notice')),
    link text,
    is_active boolean not null default true,
    published_at timestamptz not null default now(),
    expires_at timestamptz,
    created_by uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now(),
    constraint app_announcements_expiry_check
        check (expires_at is null or expires_at > published_at),
    constraint app_announcements_link_check
        check (link is null or (link like '/%' and link not like '//%'))
);

create index if not exists app_announcements_published_idx
    on public.app_announcements (published_at desc);
create index if not exists app_announcements_active_published_idx
    on public.app_announcements (published_at desc)
    where is_active = true;

alter table public.app_announcements enable row level security;
revoke all on table public.app_announcements from anon, authenticated;

commit;
